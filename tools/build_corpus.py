#!/usr/bin/env python3
"""Build stage 23's kernel corpus into driver/core/cezanne_corpus.h.

Each kernel in shaders/corpus/ is MSL (`NAME.metal`) with the AIR Apple's
`metal -c` makes of it, as LLVM 20.1.7's `llvm-dis` prints it (`NAME.ll`,
without its ModuleID line). This tool lowers the AIR with tools/air_lower.py,
compiles it with LLVM 20.1.7 for gfx90c, and writes the code and descriptor
fields the kext embeds. `--from-metal` first regenerates the AIR (needs the
Metal Toolchain). `--check` compares against the header instead of writing it.

Every kernel's user SGPRs must be the private segment buffer, then the
dispatch packet if it reads one, then kernarg (code properties 0xb or 0x9,
the layouts the kext sets up). It must use no scratch and fit its code slot.
"""
import argparse
import importlib.util
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "shaders" / "corpus"
HEADER = ROOT / "driver" / "core" / "cezanne_corpus.h"
LLVM_BIN = ROOT / "out" / "shader-target" / "llvm" / "LLVM-20.1.7-macOS-X64" / "bin"
# The order is the kernel index a submission names.
KERNELS = ["store_index", "vector_add", "group_sum", "atomic_count", "grid_2d"]
CODE_SLOT = 0x1000  # bytes per kernel in the region's code area
PROPERTIES = (0xB, 0x9)

spec = importlib.util.spec_from_file_location("air_lower", ROOT / "tools" / "air_lower.py")
air_lower = importlib.util.module_from_spec(spec)
spec.loader.exec_module(air_lower)


def run(argv, cwd=None):
    done = subprocess.run([str(a) for a in argv], capture_output=True, text=True, timeout=120, cwd=cwd)
    if done.returncode != 0:
        raise SystemExit("%s failed (%d): %s" % (Path(str(argv[0])).name, done.returncode, done.stderr.strip()))
    return done


def sections(path):
    data = path.read_bytes()
    shoff, = struct.unpack_from("<Q", data, 0x28)
    size, count, names_index = struct.unpack_from("<HHH", data, 0x3a)
    rows = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * size) for i in range(count)]
    names = data[rows[names_index][4]:rows[names_index][4] + rows[names_index][5]]
    found = {}
    for name, _, _, _, offset, length, *_ in rows:
        key = names[name:names.index(b"\0", name)].decode()
        found[key] = data[offset:offset + length]
    return found


def air_from_metal(name, tmp):
    metal = run(["xcrun", "-f", "metal"]).stdout.strip()
    air = tmp / (name + ".air")
    # Run in the corpus directory so the AIR names the source by its file name.
    run([metal, "-c", name + ".metal", "-o", air], cwd=CORPUS)
    run([LLVM_BIN / "llvm-dis", air, "-o", tmp / (name + ".dis.ll")])
    text = (tmp / (name + ".dis.ll")).read_text()
    # The AIR also records the source's absolute path; keep the file name only.
    text = text.replace(str(CORPUS.resolve()) + "/", "")
    return re.sub(r"^; ModuleID = .*\n", "", text, flags=re.M)


def build(name, air, tmp):
    (tmp / (name + ".ll")).write_text(air_lower.lower(air))
    run([LLVM_BIN / "opt", "-mcpu=gfx90c", "-O2", "-S", tmp / (name + ".ll"), "-o", tmp / (name + ".opt.ll")])
    run([LLVM_BIN / "llc", "-mcpu=gfx90c", "-filetype=obj", tmp / (name + ".opt.ll"), "-o", tmp / (name + ".o")])
    run([LLVM_BIN / "ld.lld", "-shared", tmp / (name + ".o"), "-o", tmp / (name + ".hsaco")])
    found = sections(tmp / (name + ".hsaco"))
    text, descriptor = found[".text"], found[".rodata"]
    lds, private, kernarg = struct.unpack_from("<III", descriptor, 0)
    _, rsrc1, rsrc2, properties = struct.unpack_from("<IIIH", descriptor, 44)
    if properties not in PROPERTIES:
        raise SystemExit("%s: code properties 0x%x, not 0xb or 0x9" % (name, properties))
    if private != 0 or (rsrc2 & 1) != 0:
        raise SystemExit("%s: uses scratch" % name)
    if len(text) > CODE_SLOT or len(text) % 4 != 0:
        raise SystemExit("%s: %d bytes of code" % (name, len(text)))
    return {"name": name, "code": list(struct.unpack("<%dI" % (len(text) // 4), text)), "rsrc1": rsrc1,
            "rsrc2": rsrc2, "lds": lds, "kernarg": kernarg, "properties": properties}


def header(kernels):
    out = ["// Generated by tools/build_corpus.py from shaders/corpus/ (Apple metal",
           "// 32023.883 AIR, tools/air_lower.py, LLVM 20.1.7 for gfx90c). Do not edit.",
           "#pragma once", "", "#include <stdint.h>", "", "namespace cezanne {", ""]
    for k in kernels:
        words = k["code"]
        out.append("const uint32_t kCorpus_%s[] = {" % k["name"])
        for i in range(0, len(words), 6):
            out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",")
        out.append("};")
    out += ["", "// properties: the descriptor's kernel_code_properties (0xb: segment buffer,",
            "// dispatch packet, kernarg; 0x9: no dispatch packet).",
            "struct CorpusCode {", "    const uint32_t *code;",
            "    uint32_t dwords, rsrc1, rsrc2, staticLds, kernargBytes, properties;",
            "};", "const CorpusCode kCorpusCode[] = {"]
    for k in kernels:
        out.append("    {kCorpus_%s, %d, 0x%08x, 0x%08x, %d, %d, 0x%x}," % (
            k["name"], len(k["code"]), k["rsrc1"], k["rsrc2"], k["lds"], k["kernarg"], k["properties"]))
    out += ["};", "const uint32_t kCorpusCount = %d;" % len(kernels), "", "} // namespace cezanne", ""]
    return "\n".join(out)


def generate(from_metal=False):
    kernels = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for name in KERNELS:
            if from_metal:
                (CORPUS / (name + ".ll")).write_text(air_from_metal(name, tmp))
            kernels.append(build(name, (CORPUS / (name + ".ll")).read_text(), tmp))
    return header(kernels)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--from-metal", action="store_true", help="regenerate the AIR from the MSL first")
    parser.add_argument("--check", action="store_true", help="compare with the header instead of writing it")
    args = parser.parse_args(argv)
    text = generate(args.from_metal)
    if args.check:
        if HEADER.read_text() != text:
            print("%s differs from the corpus build" % HEADER.relative_to(ROOT), file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
